#!/usr/bin/env bash
# Install or remove the ForgeMesh Control Center desktop launcher.
#
# The launcher starts the Electron shell from *this* checkout, so the app keeps
# using the same venv, data dir and dashboard build as `scripts/start.sh`.
# Everything lands in the user's home directory: no sudo, no system packages.
#
#   scripts/install_desktop.sh              install / refresh
#   scripts/install_desktop.sh --uninstall  remove again
#
# Re-running is safe: the wrapper and the .desktop entry are rewritten from the
# current checkout path, so moving the repository just needs a second run.
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
DESKTOP_DIR="$ROOT/desktop"
ELECTRON_BIN="$DESKTOP_DIR/node_modules/electron/dist/electron"
ICON_SRC="$DESKTOP_DIR/assets/icon.png"

BIN_DIR="${XDG_BIN_HOME:-$HOME/.local/bin}"
APPS_DIR="${XDG_DATA_HOME:-$HOME/.local/share}/applications"
WRAPPER="$BIN_DIR/forgemesh-control-center"
DESKTOP_FILE="$APPS_DIR/forgemesh-control-center.desktop"
WM_CLASS="forgemesh-control-center"
ACTION="install"

usage() {
    cat <<'EOF'
Usage: scripts/install_desktop.sh [--uninstall] [--prefix DIR]

  --uninstall     Remove the launcher, the wrapper and the .desktop entry.
  --prefix DIR    Where to put the wrapper (default: ~/.local/bin).
  -h, --help      Show this help.

Nothing here needs sudo and nothing is deleted outside the paths this script
created itself.
EOF
}

while [[ $# -gt 0 ]]; do
    case "$1" in
        --uninstall) ACTION="uninstall" ;;
        --prefix) BIN_DIR="${2:?--prefix needs a directory}"; WRAPPER="$BIN_DIR/forgemesh-control-center"; shift ;;
        -h|--help) usage; exit 0 ;;
        *) echo "Unknown option: $1" >&2; usage >&2; exit 2 ;;
    esac
    shift
done

log() { printf '\033[1;36m[desktop]\033[0m %s\n' "$*"; }
warn() { printf '\033[1;33m[desktop]\033[0m %s\n' "$*" >&2; }
fail() { printf '\033[1;31m[desktop]\033[0m %s\n' "$*" >&2; exit 1; }

# --- uninstall ---------------------------------------------------------------
if [[ "$ACTION" == "uninstall" ]]; then
    removed=0
    for target in "$WRAPPER" "$DESKTOP_FILE"; do
        if [[ -e "$target" ]]; then
            rm -f "$target"
            log "removed $target"
            removed=1
        else
            log "not present, nothing to remove: $target"
        fi
    done
    if command -v update-desktop-database >/dev/null 2>&1; then
        update-desktop-database "$APPS_DIR" 2>/dev/null || true
    fi
    if command -v gtk-update-icon-cache >/dev/null 2>&1; then
        gtk-update-icon-cache -q "${XDG_DATA_HOME:-$HOME/.local/share}/icons/hicolor" 2>/dev/null || true
    fi
    [[ $removed -eq 1 ]] && log "launcher removed" || log "nothing had been installed"
    exit 0
fi

# --- install -----------------------------------------------------------------
[[ -f "$DESKTOP_DIR/main.js" ]] || fail "no desktop shell at $DESKTOP_DIR (wrong checkout path?)"
[[ -f "$ICON_SRC" ]] || fail "missing icon: $ICON_SRC (run: .venv/bin/python scripts/make_desktop_icons.py)"
[[ -x "$ELECTRON_BIN" ]] || fail "Electron is not installed in this checkout. Run: npm --prefix desktop install"
[[ -f "$ROOT/frontend/dist/index.html" ]] || warn "frontend/dist/index.html is missing; the shell will report a startup failure until you build the dashboard (npm --prefix frontend run build)"

mkdir -p "$BIN_DIR" "$APPS_DIR"

# The wrapper hardcodes the absolute checkout path on purpose: a .desktop entry
# has no way to discover it, and a relative path would break when the launcher
# is started from a different working directory.
cat >"$WRAPPER" <<EOF
#!/usr/bin/env bash
# Generated by scripts/install_desktop.sh - starts the ForgeMesh desktop shell
# from this checkout. Re-run that script after moving the repository.
set -euo pipefail

REPO="$ROOT"
ELECTRON="\$REPO/desktop/node_modules/electron/dist/electron"

if [[ ! -x "\$ELECTRON" ]]; then
    echo "ForgeMesh: Electron is missing at \$ELECTRON" >&2
    echo "Fix it with: npm --prefix \"\$REPO/desktop\" install" >&2
    exit 1
fi

cd "\$REPO"
exec "\$ELECTRON" --class=$WM_CLASS "\$REPO/desktop" "\$@"
EOF
chmod 0755 "$WRAPPER"
log "wrote wrapper $WRAPPER"

# Reuse the generated application icon instead of inventing a second one.
ICON_TARGET="$ICON_SRC"
if [[ -d "${XDG_DATA_HOME:-$HOME/.local/share}/icons" ]]; then
    HICOLOR="${XDG_DATA_HOME:-$HOME/.local/share}/icons/hicolor/256x256/apps"
    mkdir -p "$HICOLOR"
    cp -f "$ICON_SRC" "$HICOLOR/forgemesh-control-center.png"
    ICON_TARGET="$HICOLOR/forgemesh-control-center.png"
    log "installed icon $ICON_TARGET"
fi

cat >"$DESKTOP_FILE" <<EOF
[Desktop Entry]
Type=Application
Version=1.0
Name=ForgeMesh Control Center
GenericName=Control Center
Comment=AI multi-agent server control center
Exec="$WRAPPER"
Icon=$ICON_TARGET
Terminal=false
Categories=Development;
Keywords=forgemesh;agents;dashboard;control;
StartupWMClass=$WM_CLASS
EOF
chmod 0644 "$DESKTOP_FILE"
log "wrote $DESKTOP_FILE"

if command -v update-desktop-database >/dev/null 2>&1; then
    update-desktop-database "$APPS_DIR" 2>/dev/null || true
fi

if command -v desktop-file-validate >/dev/null 2>&1; then
    if desktop-file-validate "$DESKTOP_FILE"; then
        log "desktop-file-validate: OK"
    else
        warn "desktop-file-validate reported problems (see above)"
    fi
else
    log "desktop-file-validate is not installed; skipping validation"
fi

case ":$PATH:" in
    *":$BIN_DIR:"*) ;;
    *) warn "$BIN_DIR is not on PATH; add it if you want to run forgemesh-control-center from a terminal" ;;
esac

log "done. Launch it from your applications menu, or run: $WRAPPER"
