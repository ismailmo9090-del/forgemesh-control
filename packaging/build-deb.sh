#!/usr/bin/env bash
# Build a self-contained .deb for ForgeMesh Control Center.
#
#   packaging/build-deb.sh
#
# Layout produced:
#   /opt/forgemesh/app          project tree (source, config, frontend/dist)
#   /opt/forgemesh/venv         Python dependencies (created by postinst)
#   /usr/bin/fmb                browser runtime CLI
#   /usr/bin/fmc                control server CLI
#   /usr/bin/forgemesh-control  desktop launcher (starts server + dashboard)
#
# The package is architecture-independent; Python wheels are fetched during
# configuration, so the target machine needs internet for the first install.
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$ROOT"

NAME="forgemesh-control"
ARCH="all"
VERSION="$(python3 - <<'PY'
import tomllib
from pathlib import Path
print(tomllib.loads(Path("pyproject.toml").read_text())["project"]["version"])
PY
)"

BUILD="$ROOT/build/deb"
STAGE="$BUILD/${NAME}_${VERSION}_${ARCH}"
DIST="$ROOT/dist"
APP="$STAGE/opt/forgemesh/app"

log() { printf '\033[1;36m[deb]\033[0m %s\n' "$*"; }
fail() { printf '\033[1;31m[deb]\033[0m %s\n' "$*" >&2; exit 1; }

[[ -f frontend/dist/index.html ]] || fail "frontend/dist is missing. Run: (cd frontend && npm ci && npm run build)"
command -v dpkg-deb >/dev/null 2>&1 || fail "dpkg-deb not found (install dpkg)."

log "Staging $NAME $VERSION"
rm -rf "$STAGE"
mkdir -p "$APP" \
    "$STAGE/DEBIAN" \
    "$STAGE/usr/bin" \
    "$STAGE/usr/share/applications" \
    "$STAGE/usr/share/icons/hicolor/128x128/apps" \
    "$STAGE/usr/share/icons/hicolor/512x512/apps" \
    "$STAGE/usr/lib/systemd/user"

# --- project tree ------------------------------------------------------------
cp -a src "$APP/src"
cp -a config "$APP/config"
cp -a scripts "$APP/scripts"
mkdir -p "$APP/frontend"
cp -a frontend/dist "$APP/frontend/dist"
cp -a docs "$APP/docs"
rm -rf "$APP/docs/reference"
cp -a README.md LICENSE pyproject.toml .env.example "$APP/"

find "$APP" -name '__pycache__' -type d -prune -exec rm -rf {} +
find "$APP" -name '*.py[co]' -delete
chmod +x "$APP/scripts/"*.sh

# --- runtime requirements ----------------------------------------------------
python3 - "$APP/requirements.txt" <<'PY'
import sys
import tomllib
from pathlib import Path

data = tomllib.loads(Path("pyproject.toml").read_text())
deps = data["project"]["dependencies"]
Path(sys.argv[1]).write_text("\n".join(deps) + "\n")
print(f"[deb] {len(deps)} runtime requirements")
PY

# --- CLI wrappers ------------------------------------------------------------
write_wrapper() {
    target="$1"
    module="$2"
    cat >"$target" <<EOF
#!/bin/sh
# Generated by the forgemesh-control package.
export PYTHONNOUSERSITE=1
export PYTHONPATH="/opt/forgemesh/app/src\${PYTHONPATH:+:\$PYTHONPATH}"
exec /opt/forgemesh/venv/bin/python -m ${module} "\$@"
EOF
    chmod 0755 "$target"
}
write_wrapper "$STAGE/usr/bin/fmb" "forgemesh_browser.main"
write_wrapper "$STAGE/usr/bin/fmc" "forgemesh_control.main"

install -m 0755 packaging/launcher/forgemesh-control "$STAGE/usr/bin/forgemesh-control"
install -m 0755 packaging/launcher/fmw "$STAGE/usr/bin/fmw"
install -m 0755 scripts/forgemesh.sh "$STAGE/usr/bin/forgemesh"

# --- desktop integration -----------------------------------------------------
install -m 0644 packaging/desktop/forgemesh-control.desktop \
    "$STAGE/usr/share/applications/forgemesh-control.desktop"
install -m 0644 desktop/assets/icon-128.png \
    "$STAGE/usr/share/icons/hicolor/128x128/apps/forgemesh-control.png"
install -m 0644 desktop/assets/icon.png \
    "$STAGE/usr/share/icons/hicolor/512x512/apps/forgemesh-control.png"

# --- systemd user units (not enabled automatically) --------------------------
install -m 0644 packaging/systemd/forgemesh-control.service \
    "$STAGE/usr/lib/systemd/user/forgemesh-control.service"
install -m 0644 packaging/systemd/forgemesh-browser.service \
    "$STAGE/usr/lib/systemd/user/forgemesh-browser.service"
install -m 0644 packaging/systemd/forgemesh-worker.service \
    "$STAGE/usr/lib/systemd/user/forgemesh-worker.service"

# --- package metadata --------------------------------------------------------
INSTALLED_KB="$(du -sk "$STAGE" | cut -f1)"
sed -e "s/^Version:.*/Version: ${VERSION}/" \
    -e "/^Description:/i Installed-Size: ${INSTALLED_KB}" \
    packaging/debian/control >"$STAGE/DEBIAN/control"
install -m 0755 packaging/debian/postinst "$STAGE/DEBIAN/postinst"
install -m 0755 packaging/debian/postrm "$STAGE/DEBIAN/postrm"
find "$STAGE" -type d -exec chmod 0755 {} +

mkdir -p "$DIST"
OUT="$DIST/${NAME}_${VERSION}_${ARCH}.deb"
log "Building $OUT"
dpkg-deb --root-owner-group --build "$STAGE" "$OUT" >/dev/null

log "Done: $OUT ($(du -h "$OUT" | cut -f1))"
dpkg-deb --info "$OUT"
